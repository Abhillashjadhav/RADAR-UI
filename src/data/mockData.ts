export const riskTrendData: RiskTrendDataPoint[] = Array.from({ length: 30 }, (_, i) => {
  const day = i + 1;
  // Create realistic trend: start at ~55, spike around day 15, settle to ~60
  const baseDelivery = 55 + Math.sin((day / 30) * Math.PI) * 20 + (Math.random() - 0.5) * 5;
  const baseCompliance = 50 + Math.sin(((day + 5) / 30) * Math.PI) * 15 + (Math.random() - 0.5) * 4;
  const baseCost = 45 + Math.sin(((day + 10) / 30) * Math.PI) * 18 + (Math.random() - 0.5) * 6;

  return {
    day,
    delivery: Math.round(Math.max(30, Math.min(90, baseDelivery))),
    compliance: Math.round(Math.max(30, Math.min(85, baseCompliance))),
    cost: Math.round(Math.max(25, Math.min(80, baseCost))),
  };
});

export const getSubTierNetwork = (supplierId: string): SubTierNode | null => {
  const supplier = suppliers.find(s => s.id === supplierId);
  if (!supplier) return null;

  const buildSubTierTree = (supplierIds: string[] | undefined, depth: number): SubTierNode[] => {
    if (!supplierIds || depth > 2) return [];

    return supplierIds.map(id => {
      const sub = suppliers.find(s => s.id === id);
      if (!sub) return null;

      const labels: Record<string, string> = {
        'SUP-004': 'PCB substrates',
        'SUP-009': 'Copper foil',
        'SUP-010': 'Capacitors',
        'SUP-017': 'Argon gas',
        'SUP-018': 'Epoxy resin',
        'SUP-007': 'Display panels',
        'SUP-012': 'Assembly services',
      };

      return {
        id: sub.id,
        name: sub.name,
        riskScore: sub.overallRiskScore,
        label: labels[sub.id] || sub.primaryImpact,
        children: buildSubTierTree(sub.subTierSuppliers, depth + 1),
      };
    }).filter(Boolean) as SubTierNode[];
  };

  return {
    id: 'QSC',
    name: 'QSC Aerospace',
    riskScore: 0,
    children: [{
      id: supplier.id,
      name: supplier.name,
      riskScore: supplier.overallRiskScore,
      children: buildSubTierTree(supplier.subTierSuppliers, 1),
    }],
  };
};

export const getSupplierById = (id: string): Supplier | undefined => {
  return suppliers.find(s => s.id === id);
};

export const getTopRisks = (count: number = 5): Supplier[] => {
  return [...suppliers]
    .sort((a, b) => b.overallRiskScore - a.overallRiskScore)
    .slice(0, count);
};

export const getCriticalCount = (): number => {
  return suppliers.filter(s => s.overallRiskScore >= 80).length;
};

export const getMediumCount = (): number => {
  return suppliers.filter(s => s.overallRiskScore >= 60 && s.overallRiskScore < 80).length;
};

export const getTotalRevenueAtRisk = (): number => {
  return suppliers.reduce((sum, s) => sum + s.revenueAtRisk, 0);
};

export const getDeliveryRiskCount = (): number => {
  return suppliers.filter(s => s.primaryImpact === 'Delivery' && s.overallRiskScore >= 60).length;
};

export const getComplianceRiskCount = (): number => {
  return suppliers.filter(s => s.primaryImpact === 'Compliance' && s.overallRiskScore >= 60).length;
};

export const getCostRiskCount = (): number => {
  return suppliers.filter(s => s.primaryImpact === 'Cost' && s.overallRiskScore >= 60).length;
};

export const searchSuppliers = (query: string): Supplier[] => {
  const lowerQuery = query.toLowerCase();
  return suppliers.filter(s =>
    s.name.toLowerCase().includes(lowerQuery) ||
    s.location.city.toLowerCase().includes(lowerQuery) ||
    s.location.country.toLowerCase().includes(lowerQuery)
  ).slice(0, 5);
};
